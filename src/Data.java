public class Data {
    // Atributos da classe
    protected int dia;
    protected int mes;
    protected int ano;

    // Construtores
    public Data() {}

    // Metodos de acesso
    public int getDia() {
        return dia;
    }

    public void setDia(int dia) {
        this.dia = dia;
    }

    public int getMes() {
        return mes;
    }

    public void setMes(int mes) {
        this.mes = mes;
    }

    public int getAno() {
        return ano;
    }

    public void setAno(int ano) {
        this.ano = ano;
    }
}
